#!/usr/bin/env python3
"""Bind, break and contradict a claim, and capture what the engine says.

The claim-binding pages make three promises a reader has to be able to check
on the page itself: a claim that names the step behind it comes back bound to
a key, a claim naming a step the pipeline does not produce is reported the way
an uncited tool is, and a claim restating a threshold the run disagrees with
is contradicted with both numbers stated. Pasting those write-ups would let
them drift the moment the wording changed, so they are captured from real
`ligase methods` runs on every docs build instead.

That makes this a test as well as a generator. Each capture declares what it
must contain *and* the exit code the CLI must return, so if an unbacked claim
ever stops failing — which is the whole of what makes a claim enforceable in
CI — the docs build fails rather than shipping a page that promises it.

Nothing here touches the repository: it all happens in a temp directory that
is thrown away.
"""

from __future__ import annotations

import io
import json
import os
import sys
import tempfile
from contextlib import redirect_stdout
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "lib/claims.generated.ts"

#: A tiny reference, so the pipeline needs no external tool and no network.
#: One contig, named as an accession, which is what `prov::pin` reads.
REFERENCE = ">K03455.1 Human immunodeficiency virus 1 (HXB2)\nACGTACGTACGTACGT\n"

#: The pipeline, with one claim and one threshold. Both are substituted per
#: capture: the claim because that is the edit a manuscript goes through, and
#: the threshold because the drift this exists to catch runs the other way --
#: the analysis moves and the sentence stays.
PIPELINE = '''import ligase as lg
from ligase.types import Alignment, Reference

hxb2 = lg.reference("refs/HXB2.fasta", organism="HIV-1", build="HXB2")


@lg.step
def call(ref: Reference, min_freq: float = 0.01) -> Alignment:
    """Call variants above a minimum allele frequency."""
    return lg.sh("cat {{ref}} > {{out}} && echo {{min_freq}} > /dev/null")


pipe = lg.Pipeline(
    call(hxb2, min_freq={min_freq}),
    claims=[
        {claim}
    ],
)
'''

#: A claim that restates the threshold the paper reports. It is the same
#: sentence in both of the first two captures; what differs between them is
#: what the pipeline ran.
THRESHOLD = """lg.Claim(
            "variants were called above 1% allele frequency",
            step="call",
            parameter="min_freq",
            value=0.01,
        ),"""

#: A number from a step this pipeline no longer has -- the analysis was
#: rewritten and the sentence stayed.
UNBACKED = """lg.Claim(
            "three resistance mutations were found",
            step="resistance",
        ),"""


def run_cli(*argv: str) -> tuple[str, int]:
    """Run the CLI in-process and return what it printed and its exit code."""
    from ligase.cli import main

    printed = io.StringIO()
    with redirect_stdout(printed):
        code = main(list(argv))
    return printed.getvalue().rstrip("\n"), code


def expect(key: str, text: str, code: int, contains: str, wanted: int) -> str:
    """Fail the build when a write-up no longer says what the page says."""
    if contains not in text:
        raise SystemExit(
            f"{key}: expected the write-up to contain {contains!r}, got:\n\n"
            f"{text}\n\n"
            f"A claim-binding page claims this. Either the engine changed or "
            f"the page is now wrong; both need a human."
        )
    if code != wanted:
        raise SystemExit(
            f"{key}: expected `ligase methods` to exit {wanted} and it exited "
            f"{code}.\n\n{text}\n\n"
            f"The pages promise that an unbacked claim fails and a bound one "
            f"does not, which is what makes a claim enforceable in CI."
        )
    return text


def main() -> int:
    """Run the three write-ups and write the module the pages import."""
    try:
        import ligase  # noqa: F401
    except ImportError as exc:
        print(
            f"error: cannot import ligase ({exc}). The claim-binding pages are "
            "generated by running a pipeline, so the docs build needs the "
            "package.",
            file=sys.stderr,
        )
        return 1

    here = Path.cwd()
    captured: dict[str, str] = {}
    with tempfile.TemporaryDirectory(prefix="ligase-claims-") as tmp:
        project = Path(tmp)
        (project / "refs").mkdir()
        (project / "refs/HXB2.fasta").write_text(REFERENCE)

        os.chdir(project)
        try:
            # Each capture rewrites the one claim and writes the pipeline up
            # again. The step itself never changes, so the second and third
            # runs are served from the cache -- which is the point: a claim
            # is in no key, so editing a manuscript reruns nothing.
            for key, claim, threshold, contains, code in (
                # The paper says 1% and the pipeline ran at 1%.
                ("bound", THRESHOLD, "0.01", "rests on `call`", 0),
                # Six months later the threshold moved to 5% and the
                # sentence did not. Nothing failed; nobody noticed.
                ("contradicted", THRESHOLD, "0.05", "One of the two is wrong", 1),
                # And a number from a step the analysis no longer has.
                ("unbacked", UNBACKED, "0.01", "has nothing behind it", 1),
            ):
                (project / "pipeline.py").write_text(
                    PIPELINE.format(claim=claim, min_freq=threshold)
                )
                text, exited = run_cli("methods")
                captured[key] = expect(key, text, exited, contains, code)
        finally:
            os.chdir(here)

    described = {
        "bound": (
            "`ligase methods` on a pipeline whose claim restates the "
            "threshold the run used."
        ),
        "contradicted": (
            "The same sentence after the threshold moved to 5% and the paper "
            "did not. `ligase methods` exits non-zero."
        ),
        "unbacked": (
            "A number from a step the pipeline no longer has. `ligase "
            "methods` exits non-zero."
        ),
    }

    lines = [
        "// Generated by web/scripts/capture_claims.py. Do not edit.",
        "//",
        "// Produced by running a real one-step pipeline in a temporary",
        "// directory three times, with one claim rewritten each time, and",
        "// recording what `ligase methods` printed and what it exited with.",
        "// An unbacked claim failing and a bound one not is what makes a",
        "// claim enforceable in CI, so the build fails if either changes.",
        "",
        "export const claims = {",
    ]
    for key, text in captured.items():
        lines.append(f"  /** {described[key]} */")
        lines.append(f"  {key}: {json.dumps(text)},")
    lines += ["} as const", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"bound, contradicted and broke a claim, and captured {len(captured)} write-ups"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
