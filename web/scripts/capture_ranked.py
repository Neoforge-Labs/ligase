#!/usr/bin/env python3
"""Reorder a ranking and a set, run both, and capture what the engine does.

The ranked-list guide makes one claim that no other page makes and that the
whole `RankedList` kind rests on: reordering the rows of a ranking changes its
result, and reordering the rows of a set does not. A page cannot assert that
and be believed, so this proves it -- by building a real one-step pipeline over
one file of each kind in a temporary directory, running it, reordering each
input in turn, and recording what the real CLI printed each time.

That makes this a test as well as a generator. If a ranking ever stops
rerunning when its rows move, or a set ever starts, the docs build fails rather
than shipping a page that promises the opposite of what the engine does.

Nothing here touches the repository: it all happens in a temp directory that is
thrown away.
"""

from __future__ import annotations

import io
import json
import os
import sys
import tempfile
from contextlib import redirect_stdout
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "lib/ranked.generated.ts"

#: A ranking, best first. The order is the result.
RANKED = "id\tscore\nTP53\t12.4\nBRCA1\t9.1\nEGFR\t7.7\nNKX2-1\t3.2\n"

#: The same four rows, reordered and otherwise untouched.
RANKED_REORDERED = "id\tscore\nEGFR\t7.7\nTP53\t12.4\nNKX2-1\t3.2\nBRCA1\t9.1\n"

#: A curated set. The order says nothing.
TRUTH = "id\nTP53\nEGFR\nPTEN\n"

#: The same three rows, reordered and otherwise untouched.
TRUTH_REORDERED = "id\nPTEN\nTP53\nEGFR\n"

#: The pipeline, which needs no external tool: the body is Python, so what is
#: being measured is the inputs' canonical forms and nothing else.
PIPELINE = '''import ligase as lg
from pathlib import Path

ranked = lg.ranked_list("results/ranked.tsv", organism="Homo sapiens")
truth = lg.entity_set("truth/known.tsv", organism="Homo sapiens")


@lg.step
def score(ranked: lg.RankedList, truth: lg.EntitySet) -> lg.RankedList:
    """Mark each ranked row a hit or a miss against the truth set."""

    def produce(out: Path) -> None:
        known = {
            line.split("\\t")[0]
            for line in Path(truth.file).read_text().splitlines()[1:]
        }
        rows = Path(ranked.file).read_text().splitlines()
        lines = [rows[0] + "\\thit"]
        for row in rows[1:]:
            lines.append(f"{row}\\t{row.split(chr(9))[0] in known}")
        out.write_text("\\n".join(lines) + "\\n")

    return lg.write(produce)


pipeline = lg.Pipeline(score(ranked, truth))
'''


def run_cli(*argv: str) -> str:
    """Run the CLI in-process and return everything it printed."""
    from ligase.cli import main

    printed = io.StringIO()
    with redirect_stdout(printed):
        main(list(argv))
    return printed.getvalue().rstrip("\n")


def expect(key: str, text: str, must_contain: str) -> str:
    """Fail the build when an output no longer says what the page says it does."""
    if must_contain not in text:
        raise SystemExit(
            f"{key}: expected the output to contain {must_contain!r}, got:\n\n"
            f"{text}\n\n"
            f"The ranked-list guide claims this. Either the engine changed or "
            f"the page is now wrong; both need a human."
        )
    return text


def main() -> int:
    """Run the two reorderings and write the module the page imports."""
    try:
        import ligase  # noqa: F401
    except ImportError as exc:
        print(
            f"error: cannot import ligase ({exc}). The ranked-list page is "
            "generated by running a pipeline, so the docs build needs the "
            "package.",
            file=sys.stderr,
        )
        return 1

    here = Path.cwd()
    with tempfile.TemporaryDirectory(prefix="ligase-ranked-") as tmp:
        project = Path(tmp)
        (project / "results").mkdir()
        (project / "truth").mkdir()
        (project / "results/ranked.tsv").write_text(RANKED)
        (project / "truth/known.tsv").write_text(TRUTH)
        (project / "pipeline.py").write_text(PIPELINE)

        os.chdir(project)
        try:
            captured = {
                "firstRun": expect("firstRun", run_cli("run"), "ran"),
                "unchanged": expect("unchanged", run_cli("run"), "from cache"),
                "rankingReordered": "",
                "setReordered": "",
            }

            # Reorder the ranking. Same rows, same scores, different order --
            # which is a different answer to "which of these matters most?",
            # so the step has to run again.
            (project / "results/ranked.tsv").write_text(RANKED_REORDERED)
            captured["rankingReordered"] = expect(
                "rankingReordered", run_cli("run"), "ran"
            )

            # Reorder the set. Same rows, so the same set, so nothing to do --
            # the prefilter sees a changed file, canonicalises it, and finds
            # the engine has seen this set before.
            (project / "truth/known.tsv").write_text(TRUTH_REORDERED)
            captured["setReordered"] = expect(
                "setReordered", run_cli("run"), "from cache"
            )
        finally:
            os.chdir(here)

    described = {
        "firstRun": "`ligase run` on a fresh ranking and truth set.",
        "unchanged": "`ligase run` again with nothing changed.",
        "rankingReordered": "`ligase run` after reordering the ranking's rows.",
        "setReordered": "`ligase run` after reordering the truth set's rows.",
    }

    lines = [
        "// Generated by web/scripts/capture_ranked.py. Do not edit.",
        "//",
        "// Produced by running a real one-step pipeline in a temporary",
        "// directory, reordering each of its two inputs in turn, and recording",
        "// what the CLI printed. The ranking rerunning and the set not is the",
        "// whole of D41, so the build fails if either stops being true.",
        "",
        "export const ranked = {",
    ]
    for key, text in captured.items():
        lines.append(f"  /** {described[key]} */")
        lines.append(f"  {key}: {json.dumps(text)},")
    lines += ["} as const", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"reordered a ranking and a set, and captured {len(captured)} runs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
