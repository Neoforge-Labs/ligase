#!/usr/bin/env python3
"""Run the quickstart exactly as the page tells a reader to, and capture it.

The quickstart claims that every command on it was run and every output is
real. That claim decays the moment somebody edits the page, so it is not a
claim -- it is a build step. This creates the two files the page asks the
reader to create, writes the same `pipeline.py`, and runs `check`, `run`,
`run` again and `methods` through the real CLI in a temporary directory.

It therefore also tests the quickstart. If `lg.write` changes shape, if a
step's output stops being cached on an unchanged second run, or if the CLI's
wording moves, the docs build fails rather than shipping a page whose
promised output no longer matches what a reader would see.

Nothing here touches the repository: it all happens in a temp directory that
is thrown away.
"""

from __future__ import annotations

import io
import json
import os
import re
import sys
import tempfile
from contextlib import redirect_stdout
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "lib/quickstart.generated.ts"
PAGE = Path(__file__).resolve().parents[1] / "content/start/quickstart.mdx"

# Exactly the files the page tells the reader to create.
GENOME = """>1 contig one
ACGTACGTACGTACGTACGT
>2 contig two
TTTTCCCCGGGGAAAATTTT
"""

ALIGNMENT_WRONG = (
    "@HD\tVN:1.6\tSO:coordinate\n"
    "@SQ\tSN:chr1\tLN:20\tM5:a965a71aa3690f605935c54d320905ab\n"
    "@SQ\tSN:chr2\tLN:20\tM5:89c2d6e069f386bafb1a0c811ba821f4\n"
    "@RG\tID:rg0\tSM:sample01\tPL:ILLUMINA\n"
    "read1\t0\tchr1\t1\t60\t10M\t*\t0\t0\tACGTACGTAC\tIIIIIIIIII\tRG:Z:rg0\n"
)

# The same file after the page's `sed`: contigs renamed to match the FASTA.
ALIGNMENT_FIXED = ALIGNMENT_WRONG.replace("SN:chr", "SN:").replace("\tchr1\t", "\t1\t")


def from_page(marker: str) -> str:
    """A fenced block from the quickstart page, by its info string.

    Read from the page rather than kept here, so that what this script runs
    is by construction the same text the reader is told to write. A copy in
    two places is a copy that will disagree.
    """
    page = PAGE.read_text(encoding="utf-8")
    fence = re.search(
        rf"^```{re.escape(marker)}\n(.*?)^```$", page, re.MULTILINE | re.DOTALL
    )
    if fence is None:
        raise SystemExit(
            f"{PAGE.name}: no ```{marker} block. The quickstart is generated by "
            f"running what the page says, so the block has to be findable."
        )
    return fence.group(1)


def run_cli(*argv: str) -> str:
    """Run the CLI in-process and return everything it printed."""
    from ligase.cli import main

    printed = io.StringIO()
    with redirect_stdout(printed):
        main(list(argv))
    return printed.getvalue().rstrip("\n")


def exit_code(*argv: str) -> int:
    """Run the CLI in-process and return only its exit code.

    The quickstart claims `inspect` exits non-zero on a mismatch, which is
    the whole reason it composes in a shell. A claim about an exit code has
    to be checked by reading one.
    """
    from ligase.cli import main

    with redirect_stdout(io.StringIO()):
        return main(list(argv))


def expect(key: str, text: str, must_contain: str) -> str:
    """Fail the build when an output no longer says what the page says it does."""
    if must_contain not in text:
        raise SystemExit(
            f"{key}: expected the output to contain {must_contain!r}, "
            f"got:\n\n{text}\n\n"
            f"The quickstart page describes this step's result. Either the engine "
            f"changed or the page is now wrong; both need a human."
        )
    return text


def diagnostic_of(transcript: str) -> str:
    """Pull the diagnostic out of a `ligase check` transcript.

    The transcript opens with what was checked and closes with a count; the
    paragraph between the two is the error itself.
    """
    blocks = [b for b in transcript.split("\n\n") if b.strip()]
    for block in blocks:
        if "Error in step" in block:
            return block
    raise SystemExit(f"no diagnostic found in the check transcript:\n\n{transcript}")


def main() -> int:
    """Run the quickstart and write the module the page imports."""
    try:
        import ligase  # noqa: F401
    except ImportError as exc:
        print(
            f"error: cannot import ligase ({exc}). The quickstart page is "
            "generated by running it, so the docs build needs the package.",
            file=sys.stderr,
        )
        return 1

    here = Path.cwd()
    with tempfile.TemporaryDirectory(prefix="ligase-quickstart-") as tmp:
        project = Path(tmp)
        (project / "refs").mkdir()
        (project / "aln").mkdir()
        (project / "refs/genome.fasta").write_text(GENOME)
        (project / "aln/sample01.sam").write_text(ALIGNMENT_WRONG)
        (project / "pipeline.py").write_text(from_page('python filename="pipeline.py"'))

        os.chdir(project)
        try:
            captured = {
                # No pipeline is read, which is the page's claim about
                # this command: there is nothing to write first.
                "inspect": expect(
                    "inspect",
                    run_cli("inspect", "refs/genome.fasta", "aln/sample01.sam"),
                    "ContigNamingError",
                ),
                "checkFails": expect(
                    "checkFails", run_cli("check"), "ContigNamingError"
                ),
                "checkPasses": "",
                "firstRun": "",
                "secondRun": "",
                "methods": "",
            }
            # The page says this exits non-zero so it composes in a shell.
            mismatch = exit_code("inspect", "refs/genome.fasta", "aln/sample01.sam")
            if mismatch == 0:
                raise SystemExit(
                    "inspect: the quickstart says `ligase inspect` exits "
                    "non-zero when two files disagree, and it exited 0. "
                    "Either the engine stopped seeing the mismatch or the "
                    "page is now wrong; both need a human."
                )
            # The page's fix: rename the contigs to match the reference.
            (project / "aln/sample01.sam").write_text(ALIGNMENT_FIXED)
            captured["checkPasses"] = expect(
                "checkPasses", run_cli("check"), "no problems found"
            )
            captured["firstRun"] = expect("firstRun", run_cli("run"), "ran")
            captured["secondRun"] = expect("secondRun", run_cli("run"), "from cache")
            captured["methods"] = expect("methods", run_cli("methods"), "Ligase")
        finally:
            os.chdir(here)

    # The diagnostic on its own, for <Diagnostic>, which renders one error
    # rather than a whole transcript.
    captured["checkDiagnostic"] = diagnostic_of(captured["checkFails"])

    described = {
        "inspect": "`ligase inspect` on the two files, with no pipeline written.",
        "checkDiagnostic": "The diagnostic alone, as <Diagnostic> renders it.",
        "checkFails": "`ligase check` on the mismatched files. Nothing runs.",
        "checkPasses": "`ligase check` once the contigs are renamed to match.",
        "firstRun": "`ligase run`, computing the one step.",
        "secondRun": "`ligase run` again, with nothing changed.",
        "methods": "`ligase methods`, saying how the result was produced.",
    }

    lines = [
        "// Generated by web/scripts/capture_quickstart.py. Do not edit.",
        "//",
        "// Produced by creating the quickstart's files in a temporary directory",
        "// and running the real CLI over them, so the page shows what a reader",
        "// following it would actually see.",
        "",
        "export const quickstart = {",
    ]
    for key, text in captured.items():
        lines.append(f"  /** {described[key]} */")
        lines.append(f"  {key}: {json.dumps(text)},")
    lines += ["} as const", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"ran the quickstart and captured {len(captured)} outputs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
