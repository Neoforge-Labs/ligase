#!/usr/bin/env python3
"""Port docs/*.md to web/content/**.mdx.

A migration aid, not part of the build. It runs while docs/ is still the live
source so a second pass is cheap; once the switch happens the MDX is the source
of truth and this script has done its job.

What it actually has to do, in order of how much could go wrong:

  1. MDX is JSX, so a bare `<` or `{` in prose is a syntax error where
     Markdown would have passed it through. Every one is reported rather than
     guessed at.
  2. `!!! note "Title"` admonitions become <Note>. There are five.
  3. Internal links lose their `.md` and gain a trailing slash, and the four
     root design docs move under design/, so links to them are rewritten.
  4. The nav comes from mkdocs.yml, so the _meta files keep the existing
     order and titles rather than a fresh guess at them.
"""

from __future__ import annotations

import posixpath
import re
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
CONTENT = Path(__file__).resolve().parents[1] / "content"

# docs/ paths that this script does not port.
SKIP = {
    "index.md",  # The home page is written by hand; it is a landing page now.
    "api.md",  # Generated by generate_api.py from the package's docstrings.
    "CNAME",  # Pages' custom domain is configured over the REST API, not by a file.
    # The notebooks are a section of their own, rendered from real runs by
    # render_notebooks.py rather than linked to on GitHub.
    "guide/notebooks.md",
}

# The four root-level design docs move into a section of their own.
SECTION_FOR_ROOT = "design"
ROOT_DESIGN = {"golden-example.md", "dimensions.md", "milestones.md", "decisions.md"}

ADMONITION = re.compile(r'^!!!\s+(\w+)(?:\s+"([^"]*)")?\s*$')
# Markdown autolinks. MDX reads `<https://...` as the start of a JSX tag, so
# every one has to become an ordinary link.
AUTOLINK = re.compile(r"<((?:https?|mailto):[^>\s]+)>")
# A fenced code block's delimiter, so the converters can leave fences alone.
FENCE = re.compile(r"^(\s*)(```+|~~~+)(.*)$")


# --------------------------------------------------------------------------
# Heading anchors
#
# MkDocs and rehype-slug disagree about headings containing punctuation, and
# every design doc heading has an em dash in it. `## D11 — noodles for format
# I/O` becomes `d11-noodles-for-format-io` under MkDocs, which collapses runs
# of separators, and `d11--noodles-for-format-io` under rehype-slug, which
# does not. Links written for the old anchors therefore all break.
#
# So both slugs are computed for every heading in every page, and anchors are
# translated from the old to the new. An anchor that matches no heading is
# reported: that is a link that was already broken, and `mkdocs --strict` did
# not catch it either.
# --------------------------------------------------------------------------

INLINE_LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")
HEADING = re.compile(r"^(#{2,6})\s+(.+?)\s*$", re.MULTILINE)


def heading_text(raw: str) -> str:
    """The rendered text of a heading, with inline markup removed."""
    text = INLINE_LINK.sub(r"\1", raw)
    text = text.replace("`", "")
    text = re.sub(r"\*\*([^*]*)\*\*", r"\1", text)
    text = re.sub(r"\*([^*]*)\*", r"\1", text)
    return text.strip()


def mkdocs_slug(text: str) -> str:
    """python-markdown's toc slugify: strip, collapse separators."""
    slug = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[-\s]+", "-", slug)


def github_slug(text: str) -> str:
    """github-slugger, which rehype-slug uses: strip, do not collapse."""
    slug = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return slug.replace(" ", "-")


def anchor_maps() -> dict[str, dict[str, str]]:
    """{docs-relative path: {old anchor: new anchor}} for every page."""
    maps: dict[str, dict[str, str]] = {}
    for source in DOCS.rglob("*.md"):
        rel = source.relative_to(DOCS).as_posix()
        text = source.read_text(encoding="utf-8")
        # Headings inside fenced blocks are not headings.
        without_fences = re.sub(r"^```[\s\S]*?^```", "", text, flags=re.MULTILINE)
        page: dict[str, str] = {}
        seen: dict[str, int] = {}
        for _, raw in HEADING.findall(without_fences):
            rendered = heading_text(raw)
            new = github_slug(rendered)
            # github-slugger suffixes duplicates: -1, -2, ...
            count = seen.get(new, 0)
            seen[new] = count + 1
            if count:
                new = f"{new}-{count}"
            page.setdefault(mkdocs_slug(rendered), new)
        maps[rel] = page
    return maps


ANCHORS = anchor_maps()


@dataclass
class Problem:
    """Something a human has to look at."""

    path: str
    line: int
    kind: str
    text: str


@dataclass
class Port:
    """What the port produced, and what it could not settle."""

    problems: list[Problem] = field(default_factory=list)
    written: list[Path] = field(default_factory=list)

    def note(self, path: str, line: int, kind: str, text: str) -> None:
        """Note."""
        self.problems.append(Problem(path, line, kind, text.strip()))


def split_code_spans(line: str) -> list[tuple[str, bool]]:
    """Split a line into (text, is_code) runs on backtick boundaries."""
    parts: list[tuple[str, bool]] = []
    for i, chunk in enumerate(re.split(r"(`+[^`]*`+)", line)):
        if chunk:
            parts.append((chunk, i % 2 == 1))
    return parts


def mdx_hazards(path: str, body: str, port: Port) -> None:
    """Report `<` and `{` that MDX would read as JSX, outside code."""
    in_fence = False
    fence_marker = ""
    for n, line in enumerate(body.split("\n"), start=1):
        fence = FENCE.match(line)
        if fence:
            marker = fence.group(2)
            if not in_fence:
                in_fence, fence_marker = True, marker
            elif marker.startswith(fence_marker):
                in_fence, fence_marker = False, ""
            continue
        if in_fence:
            continue
        for text, is_code in split_code_spans(line):
            if is_code:
                continue
            # `<` opening what MDX would take for a tag, and `{`, which it
            # would take for an expression.
            if re.search(r"<[A-Za-z/!]", text):
                port.note(path, n, "angle bracket outside code", line)
            if "{" in text or "}" in text:
                port.note(path, n, "brace outside code", line)


def convert_admonitions(path: str, body: str, port: Port) -> str:
    """`!!! kind "Title"` plus its indented block becomes a <Note>."""
    lines = body.split("\n")
    out: list[str] = []
    i = 0
    known = {"note", "warning", "tip", "caution", "danger", "info"}
    # The old site's `danger`/`info` were never used; map them anyway so a
    # stray one does not silently become a plain paragraph.
    kind_map = {
        "note": "note",
        "info": "note",
        "warning": "warning",
        "tip": "tip",
        "caution": "caution",
        "danger": "warning",
    }

    while i < len(lines):
        match = ADMONITION.match(lines[i])
        if not match:
            out.append(lines[i])
            i += 1
            continue

        kind, title = match.group(1).lower(), match.group(2)
        if kind not in known:
            port.note(path, i + 1, f"unknown admonition kind {kind!r}", lines[i])
            out.append(lines[i])
            i += 1
            continue

        i += 1
        block: list[str] = []
        while i < len(lines):
            line = lines[i]
            if not line.strip():
                block.append("")
                i += 1
                continue
            if line.startswith("    "):
                block.append(line[4:])
                i += 1
                continue
            break

        while block and not block[-1].strip():
            block.pop()

        attrs = f' kind="{kind_map[kind]}"'
        if title:
            attrs += f" title={jsx_title(title)}"
        out.append(f"<Note{attrs}>")
        out.append("")
        out.extend(block)
        out.append("")
        out.append("</Note>")
    return "\n".join(out)


def jsx_title(title: str) -> str:
    """A `<Note title>` attribute, rendering any backticked span as code.

    Two of the five ported admonitions have code in their titles, and a plain
    string attribute would print the backticks.
    """
    if "`" not in title:
        return '"' + title.replace('"', "&quot;") + '"'
    parts: list[str] = []
    for i, chunk in enumerate(re.split(r"`([^`]*)`", title)):
        if not chunk:
            continue
        parts.append(f"<code>{chunk}</code>" if i % 2 else chunk)
    return "{<>" + "".join(parts) + "</>}"


def route_for(rel: str) -> str:
    """The site route for a docs-relative path like `concepts/caching.md`."""
    stem = rel[: -len(".md")] if rel.endswith(".md") else rel
    if f"{stem}.md" in ROOT_DESIGN:
        return f"/{SECTION_FOR_ROOT}/{stem}/"
    if stem == "index":
        return "/"
    return f"/{stem}/"


def translate_anchor(source: str, target: str, anchor: str, port: Port) -> str:
    """Map an old MkDocs anchor onto the heading id the new site emits."""
    if not anchor:
        return ""
    page = ANCHORS.get(target)
    if page is None:
        port.note(source, 0, "anchor into an unknown page", f"{target}#{anchor}")
        return f"#{anchor}"
    new = page.get(anchor)
    if new is None:
        if anchor in page.values():
            return f"#{anchor}"
        port.note(
            source,
            0,
            "anchor matches no heading (already broken)",
            f"{target}#{anchor}",
        )
        return f"#{anchor}"
    return f"#{new}"


def rewrite_links(path: str, body: str, port: Port) -> str:
    """Point `.md` links at site routes."""

    def one(match: re.Match[str]) -> str:
        """One."""
        label, target = match.group(1), match.group(2)
        if re.match(r"^(https?:|mailto:)", target):
            return match.group(0)
        if target.startswith("#"):
            # A link within this page. Its anchor needs translating too.
            return f"[{label}]({translate_anchor(path, path, target[1:], port)})"

        anchor = ""
        if "#" in target:
            target, anchor = target.split("#", 1)

        if not target:  # a bare `#anchor` within this page
            return f"[{label}]({translate_anchor(path, path, anchor, port)})"
        if not target.endswith(".md"):
            # A link to a repository file, not a docs page -- send it to GitHub
            # rather than leaving a dead relative path.
            port.note(path, 0, "non-.md relative link left as-is", target)
            return match.group(0)

        # Resolve relative to the page's own directory inside docs/. Purely
        # lexical: these are docs-relative paths, not paths on this machine.
        here = Path(path).parent
        resolved = posixpath.normpath(posixpath.join(here.as_posix(), target))
        if resolved.startswith(".."):
            port.note(path, 0, "link escapes docs/", target)
            return match.group(0)
        fragment = translate_anchor(path, resolved, anchor, port)
        return f"[{label}]({route_for(resolved)}{fragment})"

    return re.sub(r"\[([^\]]*)\]\(([^)\s]+)\)", one, body)


def frontmatter(title: str, description: str) -> str:
    """Frontmatter."""

    def quote(value: str) -> str:
        """Quote."""
        return value.replace('"', '\\"')

    lines = ["---", f'title: "{quote(title)}"']
    if description:
        lines.append(f'description: "{quote(description)}"')
    lines += ["---", ""]
    return "\n".join(lines)


def first_paragraph(body: str) -> str:
    """The page's own first paragraph, for the meta description."""
    chunks = re.split(r"\n\s*\n", body.strip())
    for chunk in chunks:
        text = chunk.strip()
        if text.startswith("#") or text.startswith("```") or text.startswith("|"):
            continue
        flat = " ".join(text.split())
        flat = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", flat)
        flat = flat.replace("`", "").replace("*", "")
        if len(flat) > 30:
            return flat[:180].rsplit(" ", 1)[0] if len(flat) > 180 else flat
    return ""


def port_file(rel: str, port: Port) -> None:
    """Convert one docs page and write it as MDX."""
    source = DOCS / rel
    text = source.read_text(encoding="utf-8")

    heading = re.match(r"^#\s+(.+)$", text, flags=re.MULTILINE)
    title = heading.group(1).strip() if heading else Path(rel).stem
    title = re.sub(r"`([^`]*)`", r"\1", title)

    body = AUTOLINK.sub(lambda m: f"[{m.group(1)}]({m.group(1)})", text)
    mdx_hazards(rel, body, port)
    body = convert_admonitions(rel, body, port)
    body = rewrite_links(rel, body, port)

    needs_note = "<Note" in body
    imports = ""
    if needs_note:
        # <Note> is in the global MDX component map, so no import is required.
        imports = ""

    out_rel = (
        f"{SECTION_FOR_ROOT}/{Path(rel).stem}.mdx"
        if rel in ROOT_DESIGN
        else f"{Path(rel).with_suffix('.mdx').as_posix()}"
    )
    out = CONTENT / out_rel
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        frontmatter(title, first_paragraph(text)) + imports + body.rstrip() + "\n",
        encoding="utf-8",
    )
    port.written.append(out)


def main() -> int:
    """Port every page, reporting anything a human has to look at."""
    port = Port()
    sources = sorted(
        p.relative_to(DOCS).as_posix()
        for p in DOCS.rglob("*.md")
        if p.relative_to(DOCS).as_posix() not in SKIP
    )
    for rel in sources:
        port_file(rel, port)

    print(f"ported {len(port.written)} pages")
    if port.problems:
        print(f"\n{len(port.problems)} thing(s) to look at:\n")
        for problem in port.problems:
            where = f"{problem.path}:{problem.line}" if problem.line else problem.path
            print(f"  {where}  [{problem.kind}]")
            print(f"      {problem.text[:140]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
